                lspContent.AppendLine("(princ)");

                // Save to Temp
                File.WriteAllText(scriptPath, lspContent.ToString());
                
                // Save Backup
                string generatedDir = AppConfigManager.GeneratedLispFolder;
                if (!Directory.Exists(generatedDir)) Directory.CreateDirectory(generatedDir);
                string backupPath = Path.Combine(generatedDir, scriptName);
                File.WriteAllText(backupPath, lspContent.ToString());

                // Generate SCR file for CAD Batch Launch
                string scrName = $"TubeSheet_Launch_{data.ShellID}_{timestamp}.scr";
                string scrPath = Path.Combine(tempDir, scrName);
                string backupScrPath = Path.Combine(generatedDir, scrName);

                string loadPath = scriptPath.Replace("\\", "/");
                string outDwgPath = Path.Combine(generatedDir, $"TubeSheet_Output_{data.ShellID}_{timestamp}.dwg").Replace("\\", "/");
                string safeTemplatePath = templatePath.Replace("\\", "/");

                // Step 1 - Copy Template Before Launch
                File.Copy(templatePath, outDwgPath, true);

                // Phase T1F - COM Automation Diagnostic Mode

                StringBuilder log = new StringBuilder();
                log.AppendLine("--- CAD LAUNCH LOG (PHASE T1F COM AUTOMATION) ---");
                log.AppendLine($"Target DWG: {outDwgPath}");

                // 1. Launch CAD by opening the drawing directly
                ProcessStartInfo startInfo = new ProcessStartInfo
                {
                    FileName = outDwgPath,
                    UseShellExecute = true
                };

                log.AppendLine($"Launching Process: {outDwgPath}");
                Process.Start(startInfo);

                // 2. Wait for COM and connect
                dynamic gstarApp = null;
                string connectedProgId = "";
                string[] progIds = { "GstarCAD.Application", "Gcad.Application", "GCAD.Application" };
                
                int attempts = 0;
                while (gstarApp == null && attempts < 15)
                {
                    Thread.Sleep(1000);
                    attempts++;
                    foreach (var progId in progIds)
                    {
                        object obj = GetActiveCOMObject(progId);
                        if (obj != null)
                        {
                            gstarApp = obj;
                            connectedProgId = progId;
                            break;
                        }
                    }
                }

                if (gstarApp == null)
                {
                    log.AppendLine("FAILED: Could not attach to GstarCAD COM Server.");
                }
                else
                {
                    log.AppendLine($"SUCCESS: Attached to COM via ProgID '{connectedProgId}'");

                    // 3. Find the Document
                    dynamic targetDoc = null;
                    attempts = 0;
                    while (targetDoc == null && attempts < 15)
                    {
                        Thread.Sleep(1000);
                        attempts++;
                        try
                        {
                            dynamic docs = gstarApp.Documents;
                            int count = docs.Count;
                            log.AppendLine($"Poll {attempts}: {count} open documents.");

                            for (int i = 0; i < count; i++)
                            {
                                try
                                {
                                    dynamic doc = docs.Item(i);
                                    string docName = doc.FullName;
                                    log.AppendLine($"  Inspecting [0-index {i}]: {docName}");
                                    
                                    if (docName.Replace("\\", "/").Equals(outDwgPath, StringComparison.OrdinalIgnoreCase))
                                    {
                                        targetDoc = doc;
                                        break;
                                    }
                                }
                                catch
                                {
                                    // 1-indexed fallback
                                    try
                                    {
                                        dynamic doc = docs.Item(i + 1);
                                        string docName = doc.FullName;
                                        log.AppendLine($"  Inspecting [1-index {i + 1}]: {docName}");
                                        
                                        if (docName.Replace("\\", "/").Equals(outDwgPath, StringComparison.OrdinalIgnoreCase))
                                        {
                                            targetDoc = doc;
                                            break;
                                        }
                                    }
                                    catch (Exception exInner)
                                    {
                                        log.AppendLine($"  COM Exception on doc {i}: {exInner.Message}");
                                    }
                                }
                            }
                        }
                        catch (Exception ex)
                        {
                            log.AppendLine($"  COM Exception accessing Documents collection: {ex.Message}");
                        }
                    }

                    if (targetDoc != null)
                    {
                        log.AppendLine("SUCCESS: Found target document.");
                        
                        log.AppendLine("Activating document...");
                        targetDoc.Activate();
                        Thread.Sleep(1000); // Give it a moment to initialize the UI

                        try
                        {
                            log.AppendLine("Skipping diagnostic CIRCLE and TEXT; Proceeding to load LISP directly.");
                            
                            // Send Zoom Extents before loading
                            string cmd3 = "_.ZOOM\n_E\n";
                            log.AppendLine($"  SendCommand: {cmd3.Replace("\n", "\\n")}");
                            targetDoc.SendCommand(cmd3);
                            
                            log.AppendLine($"Sending LISP load command...");
                            string cmd4 = $"(load \"{loadPath}\")\n";
                            log.AppendLine($"  SendCommand: {cmd4.Replace("\n", "\\n")}");
                            targetDoc.SendCommand(cmd4);
                            
                            log.AppendLine("SUCCESS: Commands dispatched.");
                        }
                        catch (Exception cmdEx)
                        {
                            log.AppendLine($"FAILED: Exception during SendCommand - {cmdEx.Message}");
                            log.AppendLine($"Stack Trace: {cmdEx.StackTrace}");
                        }
                    }
                    else
                    {
                        log.AppendLine("FAILED: Could not find target document within 15 seconds.");
                    }
                }

                log.AppendLine("-------------------------------------------------");
                string logMessage = log.ToString();

                File.WriteAllText(Path.Combine(generatedDir, $"TubeSheet_LaunchLog_{data.ShellID}_{timestamp}.txt"), logMessage);

                return new DrawingAutomationResult
                {
                    ScriptPath = scriptPath,
                    BackupPath = backupPath,
                    ScrPath = "",
                    BackupScrPath = "",
                    CadExecutable = "COM Launch",
                    Arguments = outDwgPath,
                    ScrContent = logMessage
                };
            }
            catch (Exception ex)
            {
                throw new Exception($"Failed to launch CAD automation: {ex.Message}");
            }
        }
        
        private void TranslateCadEntityToLisp(StringBuilder lspContent, ICadEntity entity)
        {
            string colorCode = "7";
            if (entity is CadLine cl) colorCode = GetAcadColor(cl.EntityColor);
            else if (entity is CadArc ca) colorCode = GetAcadColor(ca.EntityColor);
            else if (entity is CadCircle cc) colorCode = GetAcadColor(cc.EntityColor);
            else if (entity is CadPolyline cp) colorCode = GetAcadColor(cp.EntityColor);
            else if (entity is CadDimension cd) colorCode = GetAcadColor(cd.EntityColor);
            else if (entity is CadText ct) colorCode = GetAcadColor(ct.EntityColor);
            else if (entity is CadMText cmt) colorCode = GetAcadColor(cmt.EntityColor);
            else if (entity is CadLeader leaderEntity) colorCode = GetAcadColor(leaderEntity.EntityColor);

            string layer = ResolveLayerName(entity);
            string linetype = ResolveLinetypeName(entity, layer);
            lspContent.AppendLine($"    (command \"-LAYER\" \"M\" \"{layer}\" \"C\" \"{colorCode}\" \"\" \"L\" \"{linetype}\" \"\" \"\")");

            if (entity is CadLine line)
            {
                lspContent.AppendLine($"    (setq p1 (list (+ (car pt) {line.Start.X:F4}) (+ (cadr pt) {line.Start.Y:F4})))");
                lspContent.AppendLine($"    (setq p2 (list (+ (car pt) {line.End.X:F4}) (+ (cadr pt) {line.End.Y:F4})))");
                lspContent.AppendLine("    (command \"_.LINE\" p1 p2 \"\")");
            }
            else if (entity is CadCircle circle)
            {
                lspContent.AppendLine($"    (setq cen (list (+ (car pt) {circle.Center.X:F4}) (+ (cadr pt) {circle.Center.Y:F4})))");
                lspContent.AppendLine($"    (command \"_.CIRCLE\" cen {circle.Radius:F4})");
            }
            else if (entity is CadArc arc)
            {
                float startRad = arc.StartAngle * (float)Math.PI / 180f;
                float endRad = arc.EndAngle * (float)Math.PI / 180f;
                lspContent.AppendLine($"    (setq cen (list (+ (car pt) {arc.Center.X:F4}) (+ (cadr pt) {arc.Center.Y:F4})))");
                lspContent.AppendLine($"    (entmake (list '(0 . \"ARC\")");
                lspContent.AppendLine($"                   '(8 . \"{layer}\")");
                lspContent.AppendLine($"                   (cons 10 cen)");
                lspContent.AppendLine($"                   (cons 40 {arc.Radius:F4})");
                lspContent.AppendLine($"                   (cons 50 {startRad:F4})");
                lspContent.AppendLine($"                   (cons 51 {endRad:F4})))");
            }
            else if (entity is CadPolyline polyline)
            {
                lspContent.AppendLine($"    (entmake (list '(0 . \"LWPOLYLINE\")");
                lspContent.AppendLine($"                   '(100 . \"AcDbEntity\")");
                lspContent.AppendLine($"                   '(8 . \"{layer}\")");
                lspContent.AppendLine($"                   '(100 . \"AcDbPolyline\")");
                lspContent.AppendLine($"                   (cons 90 {polyline.Vertices.Count})");
                lspContent.AppendLine($"                   (cons 70 {(polyline.IsClosed ? 1 : 0)})");
                foreach (var v in polyline.Vertices)
                {
                    lspContent.AppendLine($"                   (list 10 (+ (car pt) {v.Point.X:F4}) (+ (cadr pt) {v.Point.Y:F4}))");
                    if (v.Bulge != 0f)
                    {
                        lspContent.AppendLine($"                   (cons 42 {v.Bulge:F4})");
                    }
                }
                lspContent.AppendLine("    ))");
            }
            else if (entity is CadText text)
            {
                lspContent.AppendLine($"    (setq txt_pt (list (+ (car pt) {text.Position.X:F4}) (+ (cadr pt) {text.Position.Y:F4})))");
                string align = text.Alignment switch
                {
                    System.Drawing.StringAlignment.Center => "MC",
                    System.Drawing.StringAlignment.Far => "MR",
                    _ => "ML"
                };
                lspContent.AppendLine($"    (command \"_.TEXT\" \"J\" \"{align}\" txt_pt {text.TargetPaperSpaceHeight:F1} 0 \"{text.Text.Replace("\n", "\\P")}\")");
            }
            else if (entity is CadMText mtext)
            {
                lspContent.AppendLine($"    (setq txt_pt (list (+ (car pt) {mtext.Position.X:F4}) (+ (cadr pt) {mtext.Position.Y:F4})))");
                lspContent.AppendLine("    (entmake (list '(0 . \"MTEXT\")");
                lspContent.AppendLine("                   '(100 . \"AcDbEntity\")");
                lspContent.AppendLine($"                   '(8 . \"{layer}\")");
                lspContent.AppendLine("                   '(100 . \"AcDbMText\")");
                lspContent.AppendLine("                   (cons 10 txt_pt)");
                lspContent.AppendLine($"                   (cons 40 {mtext.TargetPaperSpaceHeight:F4})");
                lspContent.AppendLine("                   (cons 71 1)");
                lspContent.AppendLine($"                   (cons 1 \"{mtext.Text.Replace("\n", "\\\\P")}\")))");
            }
            else if (entity is CadDimension dim)
            {
                lspContent.AppendLine($"    (setq d_p1 (list (+ (car pt) {dim.StartPoint.X:F4}) (+ (cadr pt) {dim.StartPoint.Y:F4})))");
                lspContent.AppendLine($"    (setq d_p2 (list (+ (car pt) {dim.EndPoint.X:F4}) (+ (cadr pt) {dim.EndPoint.Y:F4})))");
                lspContent.AppendLine($"    (setq d_loc (list (+ (car pt) {dim.DimensionLineLocation.X:F4}) (+ (cadr pt) {dim.DimensionLineLocation.Y:F4})))");
                string overrideStr = string.IsNullOrEmpty(dim.OverrideText) ? "" : dim.OverrideText;
                
                if (dim.Type == DimensionType.Diameter)
                {
                    lspContent.AppendLine($"    (setq sel_pt (list (+ (car pt) {dim.SelectionPoint.X:F4}) (+ (cadr pt) {dim.SelectionPoint.Y:F4})))");
                    lspContent.AppendLine($"    (command \"_.DIMDIAMETER\" sel_pt \"T\" \"{overrideStr}\" d_loc)");
                }
                else
                {
                    lspContent.AppendLine($"    (command \"_.DIMLINEAR\" d_p1 d_p2 \"T\" \"{overrideStr}\" d_loc)");
                }
            }
            else if (entity is CadLeader leader)
            {
                if (leader.Vertices.Count >= 2)
                {
                    for (int i = 0; i < leader.Vertices.Count - 1; i++)
                    {
                        PointF start = leader.Vertices[i];
                        PointF end = leader.Vertices[i + 1];
                        lspContent.AppendLine($"    (setq l_p1 (list (+ (car pt) {start.X:F4}) (+ (cadr pt) {start.Y:F4})))");
                        lspContent.AppendLine($"    (setq l_p2 (list (+ (car pt) {end.X:F4}) (+ (cadr pt) {end.Y:F4})))");
                        lspContent.AppendLine("    (entmake (list '(0 . \"LINE\")");
                        lspContent.AppendLine("                   '(100 . \"AcDbEntity\")");
                        lspContent.AppendLine($"                   '(8 . \"{layer}\")");
                        lspContent.AppendLine("                   (cons 10 l_p1)");
                        lspContent.AppendLine("                   (cons 11 l_p2)))");
                    }

                    if (leader.HasArrowHead)
                    {
                        PointF tip = leader.Vertices[0];
                        PointF next = leader.Vertices[1];
                        double angle = Math.Atan2(tip.Y - next.Y, tip.X - next.X);
                        const float arrowLength = 18f;
                        const float arrowWidth = 7.5f;

                        PointF arrowPt1 = new PointF(
                            tip.X - arrowLength * (float)Math.Cos(angle) - arrowWidth * (float)Math.Sin(angle),
                            tip.Y - arrowLength * (float)Math.Sin(angle) + arrowWidth * (float)Math.Cos(angle));

                        PointF arrowPt2 = new PointF(
                            tip.X - arrowLength * (float)Math.Cos(angle) + arrowWidth * (float)Math.Sin(angle),
                            tip.Y - arrowLength * (float)Math.Sin(angle) - arrowWidth * (float)Math.Cos(angle));

                        lspContent.AppendLine($"    (setq a_tip (list (+ (car pt) {tip.X:F4}) (+ (cadr pt) {tip.Y:F4})))");
                        lspContent.AppendLine($"    (setq a_p1 (list (+ (car pt) {arrowPt1.X:F4}) (+ (cadr pt) {arrowPt1.Y:F4})))");
                        lspContent.AppendLine($"    (setq a_p2 (list (+ (car pt) {arrowPt2.X:F4}) (+ (cadr pt) {arrowPt2.Y:F4})))");
                        lspContent.AppendLine("    (entmake (list '(0 . \"SOLID\")");
                        lspContent.AppendLine("                   '(100 . \"AcDbEntity\")");
                        lspContent.AppendLine($"                   '(8 . \"{layer}\")");
                        lspContent.AppendLine("                   (cons 10 a_tip)");
                        lspContent.AppendLine("                   (cons 11 a_p1)");
                        lspContent.AppendLine("                   (cons 12 a_p2)");
                        lspContent.AppendLine("                   (cons 13 a_p2)))");
                    }
                }
            }
            lspContent.AppendLine("    (command \"-LAYER\" \"S\" \"0\" \"\")");
        }

        private void AppendGeneratedTubeSheetAnnotationsLisp(
            StringBuilder lspContent,
            Dictionary<string, List<ICadEntity>> views,
            string viewKey)
        {
            if (!views.TryGetValue(viewKey, out var entities))
            {
                return;
            }

            var targetTextCenters = entities
                .OfType<CadMText>()
                .Where(IsGeneratedTubeSheetNote)
                .Select(GetMTextCenterY)
                .ToList();

            foreach (var entity in entities)
            {
                if (entity is CadMText mtext && IsGeneratedTubeSheetNote(mtext))
                {
                    TranslateCadEntityToLisp(lspContent, entity);
                }
                else if (entity is CadLeader leader && LeaderMatchesGeneratedNote(leader, targetTextCenters))
                {
                    TranslateCadEntityToLisp(lspContent, entity);
                }
            }
        }

        private bool IsGeneratedTubeSheetNote(CadMText mtext)
        {
            return mtext.Text.Contains("NOS. TUBE HOLES", StringComparison.OrdinalIgnoreCase) ||
                   mtext.Text.Contains("HOLES EQUI.", StringComparison.OrdinalIgnoreCase);
        }

        private bool LeaderMatchesGeneratedNote(CadLeader leader, List<float> targetTextCenters)
        {
            if (leader.Vertices.Count < 2)
            {
                return false;
            }

            float landingY = leader.Vertices[leader.Vertices.Count - 1].Y;
            return targetTextCenters.Any(centerY => Math.Abs(centerY - landingY) <= 1f);
        }

        private float GetMTextCenterY(CadMText mtext)
        {
            int lineCount = Math.Max(1, mtext.Text.Split('\n').Length);
            return mtext.Position.Y + (lineCount * mtext.TargetPaperSpaceHeight * 1.5f) / 2f;
        }

        private string ResolveLayerName(ICadEntity entity)
        {
            if (entity is CadDimension dimension && !string.IsNullOrWhiteSpace(dimension.LayerName)) return dimension.LayerName;
            if (entity is CadPolyline polyline && !string.IsNullOrWhiteSpace(polyline.LayerName)) return polyline.LayerName;
            if (entity is CadHatch hatch && !string.IsNullOrWhiteSpace(hatch.LayerName)) return hatch.LayerName;
            if (entity is CadLine line && !string.IsNullOrWhiteSpace(line.LayerName)) return line.LayerName;
            if (entity is CadText text && !string.IsNullOrWhiteSpace(text.LayerName)) return text.LayerName;
            if (entity is CadMText mtext && !string.IsNullOrWhiteSpace(mtext.LayerName)) return mtext.LayerName;

            if (entity is CadDimension) return "DIMENSIONS";
            if (entity is CadText || entity is CadMText) return "TEXT";
            if (entity is CadLeader) return "LEADERS";
            if (entity is CadLine centerline && centerline.EntityColor == System.Drawing.Color.Red) return "CENTERLINE";
            if ((entity is CadCircle circle && circle.EntityColor == System.Drawing.Color.Blue) ||
                (entity is CadArc arc && arc.EntityColor == System.Drawing.Color.Blue)) return "TUBE_HOLES";

            return "BAFFLE_OUTLINE";
        }

        private string ResolveLinetypeName(ICadEntity entity, string layer)
        {
            if (entity is CadLine line && !string.IsNullOrWhiteSpace(line.LinetypeName))
            {
                return line.LinetypeName;
            }

            return layer == "CENTERLINE" ? "CENTER" : "CONTINUOUS";
        }

        private string GetAcadColor(System.Drawing.Color color)
        {
            if (color == System.Drawing.Color.Red) return "1";
            if (color == System.Drawing.Color.Yellow) return "2";
            if (color == System.Drawing.Color.Green) return "3";
            if (color == System.Drawing.Color.Cyan) return "4";
            if (color == System.Drawing.Color.Blue) return "5";
            if (color == System.Drawing.Color.Magenta) return "6";
            if (color == System.Drawing.Color.White) return "7";
            return "7";
        }

