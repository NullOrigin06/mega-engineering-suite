                string loadPath = scriptPath.Replace("\\", "/");
                string scrContent = $"(load \"{loadPath}\")\n";

                File.WriteAllText(scrPath, scrContent);
                File.WriteAllText(backupScrPath, scrContent);

                if (!File.Exists(scrPath))
